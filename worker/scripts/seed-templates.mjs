// Writes seed/templates.sql: every template problem from the game (app/src/data/problems.ts, the one
// source of the templates) as an upsert into D1 `problems` (source = 'template', id = 'tpl:<id>').
// Re-running it updates changed templates and never touches AI-made problems or play counts.
//   node scripts/seed-templates.mjs   →  then  wrangler d1 execute DB --local|--remote --file seed/templates.sql
import { createHash } from 'node:crypto';
import { mkdirSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { build } from 'esbuild';

const here = dirname(fileURLToPath(import.meta.url));
const root = resolve(here, '..');
const tmp = join(root, '.wrangler', 'seed-build');
mkdirSync(tmp, { recursive: true });
const bundle = join(tmp, 'problems.mjs');
await build({ entryPoints: [resolve(root, '../app/src/data/problems.ts')], bundle: true, format: 'esm', platform: 'node', outfile: bundle, logLevel: 'warning' });
const { PROBLEMS } = await import(pathToFileURL(bundle).href);
rmSync(tmp, { recursive: true, force: true });

const q = (v) => (v === null ? 'NULL' : `'${String(v).replaceAll("'", "''")}'`);
const now = new Date().toISOString();
const rows = PROBLEMS.map((p) => {
  const texts = p.groups.flatMap((g) => g.items.map((k) => k.text)).sort();
  const itemsHash = createHash('sha256').update(texts.join('\n')).digest('hex');
  return `INSERT INTO problems (id, source, difficulty, domain, scheme, body, items_hash, status, created_at)
VALUES (${q(`tpl:${p.id}`)}, 'template', ${q(p.tier)}, NULL, NULL, ${q(JSON.stringify(p))}, ${q(itemsHash)}, 'ready', ${q(now)})
ON CONFLICT(id) DO UPDATE SET difficulty = excluded.difficulty, body = excluded.body, items_hash = excluded.items_hash, status = 'ready';`;
});

const out = join(root, 'seed', 'templates.sql');
mkdirSync(dirname(out), { recursive: true });
writeFileSync(out, `-- Generated by scripts/seed-templates.mjs from app/src/data/problems.ts. Do not edit.\n${rows.join('\n')}\n`);
console.log(`seed/templates.sql: ${rows.length} template problems`);
